"""Regenerate the commit counts in the Individual Contributions table.

    python report/make_contributions.py

Rewrites `report/sections/contributions_table.tex` from the repository history.
Run it immediately before the final compile: the counts change with every push,
and a table that disagrees with `git shortlog` is the easiest discrepancy for an
examiner to find, since they are reading the history anyway.

Owner: Jivit collects; everyone checks their own row.
"""

from __future__ import annotations

import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "report" / "sections" / "contributions_table.tex"

# Git author name -> (display name, RTL/code, testbenches, report section)
MEMBERS = [
    (
        "Taj-786",
        "Shaik Tajuddin",
        "golden model, ISA fuzzer, build system, CI",
        r"\texttt{tb\_system}",
        "Abstract, Lit. Review, Refs., final PDF",
    ),
    (
        "Parthraj Singh Bhati",
        "Parthraj Singh Bhati",
        r"\texttt{ctrl\_unit}, \texttt{instr\_mem}, \texttt{simd\_top}",
        r"\texttt{tb\_ctrl\_unit}, \texttt{tb\_simd\_top}",
        "4.1",
    ),
    (
        "Himanshu Pandey",
        "Himanshu Pandey",
        r"\texttt{lane\_alu}, \texttt{vec\_alu}",
        r"\texttt{tb\_lane\_alu}, \texttt{tb\_vec\_alu}",
        "4.2",
    ),
    (
        "Jivit Rana",
        "Jivit Rana",
        r"\texttt{scalar\_top}, benchmark programs",
        r"\texttt{tb\_scalar\_top}",
        "4.3, this table",
    ),
    (
        "Satya Yadav",
        "Satya Yadav",
        r"\texttt{vreg\_file}, \texttt{dmem}",
        r"\texttt{tb\_vreg\_file}, \texttt{tb\_dmem}",
        "---",
    ),
]


def commit_count(author: str) -> int:
    out = subprocess.run(
        ["git", "log", "--all", "--no-merges", f"--author={author}", "--oneline"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return len([ln for ln in out.splitlines() if ln.strip()])


def commit_days(author: str) -> int:
    out = subprocess.run(
        [
            "git",
            "log",
            "--all",
            "--no-merges",
            f"--author={author}",
            "--format=%ad",
            "--date=short",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return len({ln.strip() for ln in out.splitlines() if ln.strip()})


def main() -> int:
    rows, warnings = [], []
    for author, display, rtl, tb, section in MEMBERS:
        n, days = commit_count(author), commit_days(author)
        if days < 2:
            warnings.append(f"{display}: commits on only {days} day(s)")
        rows.append(f"    {display} &\n      {rtl} &\n      {tb} &\n      {section} & {n} \\\\")

    body = "\n    \\addlinespace\n".join(rows)
    OUT.write_text(
        "%% GENERATED by report/make_contributions.py - do not edit by hand.\n"
        "%% Re-run before the final compile; counts change with every push.\n"
        "\\begin{table}[htbp]\n"
        "  \\centering\n"
        "  \\caption{Individual contributions}\n"
        "  \\label{tab:contributions}\n"
        "  \\footnotesize\n"
        "  \\begin{tabular}{@{}p{1.45cm}p{2.0cm}p{1.75cm}p{1.35cm}r@{}}\n"
        "    \\toprule\n"
        "    \\textbf{Member} & \\textbf{RTL / code} & \\textbf{Testbenches} &\n"
        "    \\textbf{Report} & \\textbf{Com.} \\\\\n"
        "    \\midrule\n"
        f"{body}\n"
        "    \\bottomrule\n"
        "  \\end{tabular}\n"
        "\\end{table}\n"
    )

    print(f"wrote {OUT.relative_to(ROOT)}")
    for author, display, *_ in MEMBERS:
        print(f"  {display:<22} {commit_count(author):>3} commits, {commit_days(author)} day(s)")
    if warnings:
        print(
            "\nWARNING - the submission checklist requires commits on at least two different days:",
            file=sys.stderr,
        )
        for w in warnings:
            print(f"  {w}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
