"""Generate the golden test vectors `tb/tb_system.v` checks against.

    python golden/gen_vectors.py              # -> sim/vectors/*.hex
    python golden/gen_vectors.py --seed 7 --bits 32

Owner: Taj.

The seed is fixed by default, so every member regenerates byte-identical files
and the committed vectors always match the committed expectations. Generated
files carry a header naming the seed that produced them -- a vector file whose
provenance nobody can reconstruct is not evidence.

Values default to 16-bit magnitudes so the lanes stay readable in GTKWave for
the video. Pass ``--bits 32`` for a full-range run.

Vector pair 0 is **crafted, not random**, because the logic benchmark runs its
compares on exactly that pair and random 16-bit values make every lane answer
the same way -- a compare test that passes with the comparator deleted. Lane by
lane it covers equal, greater, less, and a signed/wrapping case:

===== ============ ============ ======= ======= ==================================
Lane  A            B            CMPEQ   CMPLT   catches
===== ============ ============ ======= ======= ==================================
0     x            x            1       0       a comparator stuck at 0
1     x            x - 1        0       0       greater-than mistaken for less
2     x            x + 1        0       1       the ordinary less-than case
3     0xFFFFFFFF   0x00000001   0       1       an *unsigned* comparator (-1 < 1),
                                                and ADD wrapping to 0
===== ============ ============ ======= ======= ==================================

Pairs 1 to 3 stay random, so the array add is not fitted to a single hand-picked
case.
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

from golden_model import (
    ALU_ADD,
    ALU_AND,
    ALU_CMPEQ,
    ALU_CMPLT,
    ALU_OR,
    ALU_SUB,
    LANE_MASK,
    LANES,
    pack,
    to_unsigned,
    vec_op,
    write_hex,
)

# Data-memory layout, fixed by docs/spec.md. A and B are inputs; C is where the
# benchmark stores its results, so the init file covers words 0-7 only.
NVEC = 4  # 16 elements / 4 lanes
A_BASE = 0
B_BASE = 4
C_BASE = 8

DEFAULT_SEED = 11  # Project 11
DEFAULT_BITS = 16


def random_vectors(rng: random.Random, count: int, bits: int) -> list[list[int]]:
    hi = (1 << bits) - 1
    return [[rng.randint(0, hi) for _ in range(LANES)] for _ in range(count)]


def craft_compare_pair(base: list[int]) -> tuple[list[int], list[int]]:
    """Turn a random vector into the equal / greater / less / signed pair.

    See the module docstring for the table this builds. Returned as (A, B) with
    lane 0 first, so A[3] is 0xFFFFFFFF and B[3] is 1: signed CMPLT must say 1
    there and an unsigned comparator says 0.
    """
    a = [to_unsigned(base[0]), to_unsigned(base[1]), to_unsigned(base[2]), LANE_MASK]
    b = [a[0], to_unsigned(a[1] - 1), to_unsigned(a[2] + 1), 1]
    return a, b


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument(
        "--bits",
        type=int,
        default=DEFAULT_BITS,
        choices=(8, 16, 32),
        help="magnitude of the generated lane values (default 16)",
    )
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="print one summary line instead of listing every vector",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "sim" / "vectors",
        help="output directory (default sim/vectors/)",
    )
    args = parser.parse_args()

    args.out.mkdir(parents=True, exist_ok=True)
    rng = random.Random(args.seed)

    a = random_vectors(rng, NVEC, args.bits)
    b = random_vectors(rng, NVEC, args.bits)
    a[0], b[0] = craft_compare_pair(a[0])

    provenance = f"generated by golden/gen_vectors.py --seed {args.seed} --bits {args.bits}"
    header = f"{provenance}\ndo not edit by hand; regenerate with  make -C sim vectors"

    # Inputs, and the data-memory image the benchmark starts from.
    write_hex(str(args.out / "a.hex"), [pack(v) for v in a], f"operand A, 4 vectors\n{header}")
    write_hex(str(args.out / "b.hex"), [pack(v) for v in b], f"operand B, 4 vectors\n{header}")
    write_hex(
        str(args.out / "dmem_init.hex"),
        [pack(v) for v in a] + [pack(v) for v in b],
        f"data memory image: A at words {A_BASE}-{A_BASE + NVEC - 1}, "
        f"B at words {B_BASE}-{B_BASE + NVEC - 1}\n"
        f"results land at words {C_BASE}-{C_BASE + NVEC - 1}\n{header}",
    )

    # bench_add16: the 16-element array add, four vector adds.
    write_hex(
        str(args.out / "expected_add.hex"),
        [pack(vec_op(ALU_ADD, a[i], b[i])) for i in range(NVEC)],
        f"expected C = A + B, four 128-bit words\n{header}",
    )

    # bench_logic: AND, OR, CMPEQ, CMPLT on the first vector pair, in the order
    # the program stores them to words 8, 9, 10, 11.
    write_hex(
        str(args.out / "expected_logic.hex"),
        [
            pack(vec_op(ALU_AND, a[0], b[0])),
            pack(vec_op(ALU_OR, a[0], b[0])),
            pack(vec_op(ALU_CMPEQ, a[0], b[0])),
            pack(vec_op(ALU_CMPLT, a[0], b[0])),
        ],
        f"expected AND, OR, CMPEQ, CMPLT on A[0] and B[0]\n{header}",
    )

    # Kept for the report's op table rather than for a benchmark program.
    write_hex(
        str(args.out / "expected_sub.hex"),
        [pack(vec_op(ALU_SUB, a[i], b[i])) for i in range(NVEC)],
        f"expected C = A - B, four 128-bit words\n{header}",
    )

    print(f"wrote 6 hex files to {args.out}  (seed {args.seed}, {args.bits}-bit values)")
    if not args.quiet:
        print("  pair 0 is crafted: equal / greater / less / signed+wrap, lane 0 to lane 3")
        for i in range(NVEC):
            print(f"  A[{i}] = {a[i]}")
            print(f"  B[{i}] = {b[i]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
